#!/usr/bin/env node
// Builds every color output from the theme + adapter. Outputs are never edited
// by hand; `check` regenerates in memory and fails if a file has drifted.
import fs from "node:fs"
import path from "node:path"
import { pathToFileURL } from "node:url"
import { loadSystem, resolveIntent, stepHex, ROOT } from "./lib.mjs"

const HEADER = (sys) =>
  `GENERATED by color-system/tools/generate.mjs from ${sys.config.theme} + ${sys.config.adapter}. Do not edit; change the theme or adapter and run \`npm run colors:generate\`.`

// Output formats, keyed by adapter.output.format. Add one per design system
// (for example a Mantine theme object or Bootstrap Sass map) without touching rules.
const FORMATS = {
  "css-variables"(sys) {
    const { adapter, rules, theme } = sys
    const o = adapter.output
    const pv = (step) => `var(${o.paletteVarPrefix}${step})`
    const lines = [`/* ${HEADER(sys)} */`, "", `${o.selectors.light} {`]
    for (const [step, hex] of Object.entries(theme.palette)) lines.push(`  ${o.paletteVarPrefix}${step}: ${hex};`)
    for (const mode of rules.modes) {
      if (mode !== "light") lines.push("", `${o.selectors[mode]} {`)
      else lines.push("")
      for (const [token, intent] of Object.entries(adapter.tokens)) lines.push(`  --${token}: ${pv(resolveIntent(sys, intent, mode))};`)
      lines.push("}")
    }
    if (o.tailwindThemeInline?.enabled) {
      lines.push("", "@theme inline {")
      for (const token of Object.keys(adapter.tokens)) lines.push(`  ${o.tailwindThemeInline.prefix}${token}: var(--${token});`)
      lines.push("}")
    }
    return lines.join("\n") + "\n"
  },
}

// Figma variable payload: names and values only (no rules). Palette steps become
// a Primitives collection; library tokens alias them per mode.
function figmaPayload(sys) {
  const { adapter, rules, theme } = sys
  const figmaName = (step) => step.replace(/-(\d+)$/, "/$1")
  const modeName = (m) => m[0].toUpperCase() + m.slice(1)
  const primitives = Object.fromEntries(Object.entries(theme.palette).map(([s, hex]) => [figmaName(s), hex]))
  const color = {}
  for (const [token, intent] of Object.entries(adapter.tokens)) {
    color[token] = Object.fromEntries(rules.modes.map((m) => [modeName(m), figmaName(resolveIntent(sys, intent, m))]))
  }
  return JSON.stringify({ about: HEADER(sys), collections: { Primitives: { modes: ["Value"], variables: primitives }, Color: { modes: rules.modes.map(modeName), variables: color } } }, null, 2) + "\n"
}

// DTCG token file: keeps its non-color sections, rewrites the color modes.
function tokenFile(sys) {
  const tf = sys.adapter.output.tokenFile
  const file = path.join(ROOT, tf.path)
  const current = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : {}
  const next = {}
  for (const mode of sys.rules.modes) {
    next[tf.modes[mode]] = Object.fromEntries(
      Object.entries(sys.adapter.tokens).map(([token, intent]) => [token, { $type: "color", $value: stepHex(sys, resolveIntent(sys, intent, mode)) }])
    )
  }
  for (const [k, v] of Object.entries(current)) if (!(k in next)) next[k] = v
  return JSON.stringify(next, null, 2) + "\n"
}

export function buildOutputs(sys = loadSystem()) {
  const o = sys.adapter.output
  const format = FORMATS[o.format]
  if (!format) throw new Error(`No generator for output format "${o.format}"`)
  const out = { [o.file]: format(sys) }
  if (o.figmaVariables) out[o.figmaVariables] = figmaPayload(sys)
  if (o.tokenFile) out[o.tokenFile.path] = tokenFile(sys)
  return out
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const outputs = buildOutputs()
  for (const [rel, content] of Object.entries(outputs)) {
    const p = path.join(ROOT, rel)
    fs.mkdirSync(path.dirname(p), { recursive: true })
    const changed = !fs.existsSync(p) || fs.readFileSync(p, "utf8") !== content
    fs.writeFileSync(p, content)
    console.log(`${changed ? "wrote" : "unchanged"} ${rel}`)
  }
}
